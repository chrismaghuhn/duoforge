#!/usr/bin/env python3
"""Generate E3a's private encoder-6 map from the existing teacher grouping.
No model parameters or data are read. --check refuses any stale output.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python"))
from duoforge import features
from duoforge_learn.columns import columns

FIELDS = ("present", "species", "item", "ability", "nature", "moves", "pp", "move_count")

def render():
    cols = columns(features.FEATURE_NAMES, features.SLOT_FEATURE_NAMES)
    entries = [None] * len(features.FEATURE_NAMES)
    groups = ("glob", "side", "position", "occupant", "member") + FIELDS
    for group in groups:
        values = getattr(cols, group)
        for coords in __import__("numpy").ndindex(values.shape):
            index = int(values[coords])
            if entries[index] is not None:
                raise ValueError(f"duplicate column classification: {features.FEATURE_NAMES[index]}")
            entries[index] = (group, coords)
    if any(e is None for e in entries) or len(entries) != 1094:
        raise ValueError("unclassified or changed encoder-6 columns")
    frozen = json.dumps(list(zip(features.FEATURE_NAMES, entries)), separators=(",", ":"))
    lines = ["/* Generated by tools/eval/input_layout.py; do not edit. */",
             f'/* Schema SHA-256: {hashlib.sha256(frozen.encode()).hexdigest()} */',
             "static const dfi_eval_column dfi_eval_columns[DFI_EVAL_INPUT_WIDTH] = {"]
    for name, (group, coords) in zip(features.FEATURE_NAMES, entries):
        padded = list(coords) + [0] * (3 - len(coords))
        lines.append(f'    {{{json.dumps(name)}, DFI_EVAL_GROUP_{group.upper()}, '
                     + ", ".join(str(c) + "u" for c in padded) + "},")
    lines += ["};", ""]
    return "\n".join(lines)

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    target = ROOT / "src/eval/input_layout.inc"
    text = render()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            raise SystemExit("eval_input_layout_stale: regenerate tools/eval/input_layout.py")
    else:
        target.write_text(text, encoding="utf-8")

if __name__ == "__main__":
    main()
