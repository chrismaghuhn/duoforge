#!/usr/bin/env python3
"""Generate only the three Owner/HS-approved value graph inventories. No weights."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python"))
from duoforge import features
import input_layout


def specs(cfg):
    e, m, p, h, layers = (cfg[k] for k in ("embed", "member", "position", "hidden", "layers"))
    entries = [("input.unit", 2, [1], 0, 0, 0, 16384)]
    for name, rows, width in [("species", 1024, e), ("move", 1024, e), ("item", 256, e),
                              ("ability", 256, e), ("nature", 25, 8)]:
        entries.append((name, 1, [rows, width], 1, 0, 0, 0))
    dense = [("move_token", e+1, e, 32768), ("member1", 5*e+42, m, 32768),
             ("member2", m, m, 32768), ("position", 106+m, p, 32768)]
    for name, ni, no, bound in dense:
        entries.extend([(name+".w", 1, [no, ni], no, bound, ni, 1 << 40),
                        (name+".b", 4, [no], 0, 0, 0, 1 << 40)])
    for i in range(layers):
        ni = 94+4*p+4*m if i == 0 else h
        bound = 32768 if i == 0 else 1 << 31
        entries.extend([(f"torso.{i}.w", 1, [h, ni], h, bound, ni, 1 << 40),
                        (f"torso.{i}.b", 4, [h], 0, 0, 0, 1 << 40),
                        (f"norm.{i}.g", 3, [h], 0, 0, 0, 1 << 20),
                        (f"norm.{i}.b", 3, [h], 0, 0, 0, 1 << 24)])
    entries.extend([("value.w", 1, [1, h], 1, 1 << 31, h, 1 << 40),
                    ("value.b", 4, [1], 0, 0, 0, 1 << 40)])
    return entries


def render(configs=None):
    if configs is None:
        configs = json.loads((ROOT / "tools/eval/graphs.json").read_text(encoding="utf-8"))
    approved = {"full": (64, 128, 128, 640, 3, 1802441),
                "small": (32, 64, 64, 256, 2, 333769),
                "medium": (48, 96, 96, 368, 3, 773193)}
    if set(configs) != set(approved):
        raise ValueError(f"eval_graph_unclassified: {sorted(set(configs) ^ set(approved))}")
    for name, graph_id, file_max, worker_max in [("full",1001,4194304,524288),
            ("small",1002,1048576,262144),("medium",1003,2097152,393216)]:
        cfg=configs[name]
        if set(cfg)!={"id","embed","member","position","hidden","layers","parameters","file_max","worker_max"}:
            raise ValueError(f"eval_graph_fields:{name}")
        if (cfg["id"],cfg["file_max"],cfg["worker_max"])!=(graph_id,file_max,worker_max):
            raise ValueError(f"eval_graph_declaration_changed:{name}")
    names_sha = hashlib.sha256(json.dumps(list(features.FEATURE_NAMES), separators=(",", ":")).encode()).digest()
    layout_sha = bytes.fromhex(re.search(r"Schema SHA-256: ([0-9a-f]{64})", input_layout.render())[1])
    out = ["/* Generated by tools/eval/graph_registry.py; do not edit. */"]
    for name, cfg in configs.items():
        if tuple(cfg[k] for k in ("embed", "member", "position", "hidden", "layers", "parameters")) != approved[name]:
            raise ValueError(f"eval_graph_declaration_changed:{name}")
        out.append(f"static const dfi_eval_tensor_spec dfi_{name}_tensors[] = {{")
        for tensor, dtype, dims, scales, bound, ni, bias in specs(cfg):
            ds = ", ".join(str(d)+"u" for d in dims+[0]*(4-len(dims)))
            out.append(f'    {{"{tensor}", {dtype}u, {len(dims)}u, {{{ds}}}, {scales}u, {bound}u, {ni}u, UINT64_C({bias})}},')
        out += ["};", f"static const dfi_eval_graph dfi_{name}_graph = {{",
                f"    {cfg['id']}u, 1u, 6u, 1094u, UINT64_C(140737488355327), UINT64_C({cfg['file_max']}),",
                "    {"+", ".join(str(x)+"u" for x in names_sha)+"},",
                "    {"+", ".join(str(x)+"u" for x in layout_sha)+"},",
                f"    {len(specs(cfg))}u, 65536u, 32u, {cfg['worker_max']}u, 0u, {32*cfg['worker_max']}u, dfi_{name}_tensors", "};"]
    out.append("static const dfi_eval_shape dfi_shapes[] = {")
    for name, cfg in configs.items():
        dims = ", ".join(str(cfg[k])+"u" for k in ("embed", "member", "position", "hidden", "layers"))
        out.append(f'    {{&dfi_{name}_graph, "{name}", {dims}, {cfg["parameters"]}u}},')
    return "\n".join(out+["};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "src/eval/graph_registry.inc"
    text = render()
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != text:
            raise SystemExit("eval_graph_registry_stale: regenerate tools/eval/graph_registry.py")
    else:
        output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
