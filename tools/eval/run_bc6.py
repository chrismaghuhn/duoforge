#!/usr/bin/env python3
"""One Owner-local command: freeze synthetic-game splits, export BC6, check.

The Owner's checkpoint and every generated byte remain on that machine.
Return only gate-summary.json and the selected artifact's SHA-256. Never
transfer the checkpoint, artifact, input/trace files or detailed audit.
No training, discovery, download, live adoption or default-backend change.
"""
from __future__ import annotations
import argparse
from collections import Counter
import json
import os
from pathlib import Path
import platform
import re
import subprocess
import sys
import zipfile

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/"python"))
from export_bc6 import (TEACHER, BC6_MASK, METHOD, canonical, clean_commit, file_sha, sha, fail,
    outside_checkout, write_private, inspect_source, integer_parameters, pack_artifact, feature_hashes)

UNITS=(256,512,1024,2048,4096,8192,16384)
CALIBRATION_ROWS=4096
CALIBRATION_ROOTS_PER_STRATUM=32
TRACE_ROWS=16
# Presence is not a proof: each declared native runner must recompute and
# match all held-out values and independent traces. Missing platforms stay
# pending; weights never travel to our cloud/CI to fill those cells.
MATRIX={("GNU","Linux"),("Clang","Linux"),("MSVC","Windows"),("Clang","Windows"),("GNU","Windows")}


def preflight_checkpoint(path):
    """SHA before NPZ parsing, output creation, model import, build or corpus."""
    path=outside_checkout(path)
    if path.stat().st_size>256*1024*1024:fail("export_checkpoint_capacity")
    if file_sha(path)!=TEACHER:fail("export_teacher_sha256")
    with zipfile.ZipFile(path) as archive:
        if sum(e.file_size for e in archive.infolist())>256*1024*1024:fail("export_source_capacity")
    return path


def checked_json(path, digest):
    if file_sha(path)!=digest:fail("bc6_manifest_sha256")
    return json.loads(path.read_text(encoding="utf-8"))


def metadata(commit, split_sha, training_commit, training_dirty):
    from bc6_corpus import SEED
    return (f"export_commit={commit}\nexport_dirty=0\nseed={SEED}\nsplit_sha256={split_sha}\n"
            f"training_commit={training_commit}\ntraining_dirty={int(training_dirty)}\n").encode("ascii")


def private_mkdir(path):
    path=outside_checkout(path)
    path.mkdir(mode=0o700)  # refuses an existing run, even if incomplete
    return path


def calibrate(root, records, flat, model, params, oracle, engine, meta, hashes, runner, kind):
    import numpy as np
    from bc6_check import Runner, load_request, select, value_batches
    chosen=[]
    for s in ("open","closed"):
        chosen+=select([r for r in records if r["stratum"]==s],CALIBRATION_ROOTS_PER_STRATUM)
    rows=[];ids=[]
    # Predetermined 64 rows per root, no value/outcome-dependent sampling.
    for r in chosen:
        req=load_request(root,r);indices=np.flatnonzero(req["open"])
        from bc6_corpus import word
        indices=sorted(indices,key=lambda i:word(r["group"],r["key"],int(i)))[:64]
        rows.extend(req["rows"][indices]);ids.extend((r["file"],int(i)) for i in indices)
    if len(rows)!=CALIBRATION_ROWS:fail("bc6_calibration_row_count")
    rows=np.array(rows,np.float32);teacher=value_batches(model,params,rows,oracle)
    candidates=[]
    # The calibration manifest's recipe is pinned before trying a unit. The
    # final selected-unit manifest is frozen before held-out values are read.
    recipe=dict(method=METHOD,units=list(UNITS),rows=ids,selection="lowest MAE, then lower unit",
                teacher_sha256=TEACHER)
    recipe_sha=sha(canonical(recipe));write_private(root/"calibration-recipe.json",canonical(recipe),False)
    for unit in UNITS:
        try:
            tensors,scales,_=integer_parameters(flat,unit)
            data=pack_artifact(tensors,scales,engine,TEACHER,recipe_sha,meta,*hashes)
            path=root/f"calibration-u{unit}.dfeval";write_private(path,data,False)
            with Runner(runner,path,sha(data),kind) as native:
                raw=native.values(rows)
            errors=np.abs(teacher.astype(np.float64)-raw.astype(np.float64)/(1<<20))
            candidates.append(dict(unit=unit,mae=float(errors.mean()),p99=float(np.percentile(errors,99)),
                                   maximum=float(errors.max())))
        except ValueError as error:
            # A quantization representation refusal disqualifies that one
            # declared scale candidate. A runner/model/input failure aborts.
            if not str(error).startswith(("export_scale_","export_parameter_range","export_bias_bound",
                                          "export_normalization_bound")):raise
            candidates.append(dict(unit=unit,refused=str(error)))
    valid=[x for x in candidates if "refused" not in x]
    if not valid:fail("bc6_no_representable_calibration_unit")
    selected=min(valid,key=lambda x:(x["mae"],x["unit"]))
    from bc6_oracle import integer_trace
    tensors,scales,_=integer_parameters(flat,selected["unit"])
    saturation=dict(rows=16,i16_saturations=0,scope="first 16 frozen calibration rows; independent integer oracle")
    integer_trace(selected["unit"],tensors,scales,rows[:16],saturation)
    result=dict(schema=1,recipe_sha256=recipe_sha,selected_unit=selected["unit"],candidates=candidates,
                rows=len(rows),activation_sample=saturation,heldout_read=False)
    write_private(root/"calibration.json",canonical(result),False)
    return result


def make_sources(args, out, context):
    """Engine-filtered registry plus the existing pinned random-set composer.
    Each team family belongs to a split before any battle is generated.
    """
    from bc6_corpus import split_of, RANDOM_TEAMS, SEED
    from duoforge import teams
    index=json.loads((ROOT/"data/teams/index.json").read_text(encoding="utf-8"))
    ids=sorted(t["id"] for t in index["teams"])
    pool,refused=teams.load_accepted(context,ids,root=ROOT/"data/teams")
    texts={tid:(ROOT/"data/teams"/(tid+".txt")).read_text(encoding="utf-8") for tid in pool.ids}
    sources={s:[] for s in ("calibration","holdout")}
    inventory=[]
    for tid,text in texts.items():
        digest=sha(text.encode("utf-8"));split=split_of(digest)
        inventory.append(dict(id=tid,sha256=digest,split=split))
        if split in sources:sources[split].append((tid,text))
    for i,split in enumerate(sources):
        target=out/(split+"-random-teams")
        subprocess.run([sys.executable,str(ROOT/"tools/reference/random_teams.py"),
            "--checkout",str(args.showdown),"--node",args.node,"--seed",f"{SEED+i+10:016x}",
            "--count",str(RANDOM_TEAMS),"--out",str(target)],check=True)
        registry=json.loads((target/"index.json").read_text(encoding="utf-8"))
        for entry in registry["teams"]:
            text=(target/(entry["id"]+".txt")).read_text(encoding="utf-8")
            sources[split].append((entry["id"],text))
            inventory.append(dict(id=entry["id"],sha256=sha(text.encode("utf-8")),split=split))
        if len(sources[split])<2:fail("bc6_insufficient_accepted_teams")
    # Duplicate generation families across splits are a refusal, not moved
    # after row extraction. Registry content is already split by digest.
    seen={}
    for e in inventory:
        if e["sha256"] in seen and seen[e["sha256"]]!=e["split"]:fail("bc6_team_family_overlap")
        seen[e["sha256"]]=e["split"]
    return sources,dict(teams=inventory,refused=[list(x) for x in refused])


def build(args):
    build_dir=outside_checkout(args.build_dir)
    subprocess.run([args.cmake,"-S",str(ROOT),"-B",str(build_dir),"-DCMAKE_BUILD_TYPE=Release",
        "-DBUILD_TESTING=ON","-DDUOFORGE_ENABLE_IPO=ON","-DDUOFORGE_WARNINGS_AS_ERRORS=ON",
        "-DDUOFORGE_PYTHON="+sys.executable,"-DDUOFORGE_LEARN_PYTHON="+sys.executable],check=True)
    subprocess.run([args.cmake,"--build",str(build_dir),"--config","Release","--target",
        "duoforge_bc6_runner","duoforge_shared","--parallel",os.environ.get("DUOFORGE_JOBS","2")],check=True)
    def locate(names):
        paths=[p for name in names for p in build_dir.rglob(name) if p.is_file() and
               "CMakeFiles" not in p.parts]
        if len(paths)!=1:fail("bc6_build_output_ambiguous")
        return paths[0].resolve()
    return locate(("duoforge_bc6_runner.exe","duoforge_bc6_runner")),locate(
        ("duoforge_shared.dll","libduoforge_shared.so","libduoforge_shared.dylib","libduoforge_shared.dll"))


def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--checkpoint",required=True,type=Path)
    p.add_argument("--out",type=Path)
    p.add_argument("--build-dir",type=Path)
    p.add_argument("--training-commit",help="actual source-training provenance, from Owner's archive")
    p.add_argument("--preflight-only",action="store_true",help="SHA-verified metadata only; no output or build")
    p.add_argument("--training-dirty",action="store_true",help="source-training checkout was dirty (never guess clean)")
    p.add_argument("--showdown",type=Path,default=os.environ.get("DUOFORGE_PS_REFERENCE_DIR"))
    p.add_argument("--node",default=os.environ.get("DUOFORGE_NODE","node"))
    p.add_argument("--cmake",default="cmake")
    p.add_argument("--runner",type=Path,action="append",default=[],help="additional local native compiler/profile bridge")
    args=p.parse_args(argv)
    # Deliberately before lock, imports, build, directory creation or parsing.
    checkpoint_path=preflight_checkpoint(args.checkpoint)
    if args.preflight_only:
        from duoforge_learn import checkpoint
        params,config=checkpoint.load_trained(checkpoint_path)
        mask=checkpoint.ext_supported_of(config)
        print(json.dumps(dict(teacher_sha256=TEACHER,encoder=checkpoint.encoder_of(config),
            source_mask=mask,source_mask_hex=hex(mask),registered_mask_hex=hex(BC6_MASK),
            graph=config["model"],graph_mask_matches=mask==BC6_MASK,
            trained_file_transferred=False,weights_printed=False,artifact_exported=False,fidelity_gates="NOT_RUN")))
        return 0
    if args.out is None or args.build_dir is None or args.training_commit is None:
        fail("bc6_run_requires_out_build_dir_training_commit")
    if not os.environ.get("DUOFORGE_MACHINE_LOCK_HELD"):fail("bc6_owner_machine_lock_required")
    if not re.fullmatch("[0-9a-f]{40}",args.training_commit):fail("export_training_provenance")
    if args.showdown is None:fail("bc6_pinned_showdown_required")
    commit=clean_commit(ROOT)
    from bc6_corpus import PS_PIN, SEARCH, plan, collect
    if subprocess.check_output(["git","-C",str(args.showdown),"rev-parse","HEAD"],text=True).strip()!=PS_PIN:
        fail("bc6_showdown_pin")
    if not subprocess.check_output([args.node,"--version"],text=True).startswith("v22."):fail("bc6_node_22_required")
    from duoforge import features
    from duoforge_learn import checkpoint
    from duoforge_learn.columns import columns
    # Fail a source/graph mismatch before constructing a private run or doing
    # a build. No feature mask is inferred, widened or relabelled here.
    params,config=checkpoint.load_trained(checkpoint_path);cols=columns()
    flat,inventory,omitted=inspect_source(params,config,features,cols)
    old_umask=os.umask(0o077)
    try:
        out=private_mkdir(args.out)
        runner,library=build(args)
        os.environ["DUOFORGE_LIBRARY"]=str(library)
        os.environ["JAX_PLATFORMS"]="cpu"
        # No library/model has been imported before the exact source SHA pin.
        import numpy as np
        import jax
        from duoforge import features, data
        from duoforge_live import data as live_data
        from duoforge_learn import checkpoint
        from duoforge_learn.columns import columns
        from bc6_oracle import float_value,integer_trace
        from bc6_check import Runner,select,evaluate
        import bc6_gates as gates
        model=checkpoint.trained_model(config,params)
        oracle=jax.jit(lambda p,x:float_value(p,config["model"],cols,x))
        tables=live_data.for_config(config)
        context=tables.context()
        kind=context.config["data_kind"]
        values=subprocess.check_output([str(runner),"--context",str(kind)],text=True).split()
        engine=dict(fingerprint=values[0],species_count=int(values[1]),move_count=int(values[2]),
                    semantics=int(values[3]),context_schema=int(values[4]),commit=commit)
        if context.fingerprint().hex()!=engine["fingerprint"]:fail("bc6_library_runner_context")
        sources,registry=make_sources(args,out,context)
        generator=dict(showdown=PS_PIN,node=subprocess.check_output([args.node,"--version"],text=True).strip(),
                       sources={name:file_sha(ROOT/"tools/reference"/name) for name in
                                ("ps_play.js","ps_trace.js","ps_client.js","ps_random_teams.js","random_teams.py")})
        split=plan(registry,engine,generator);split_data=canonical(split);split_sha=sha(split_data)
        write_private(out/"split.json",split_data,False)
        corpora={}
        for s in ("calibration","holdout"):
            corpora[s]=collect(s,[g for g in split["games"] if g["split"]==s],out,checkpoint_path,tables,model,params,
                               args.node,args.showdown,sources[s])
        chosen=[]
        for s in gates.STRATA:
            chosen+=select([r for r in corpora["holdout"]["requests"] if r["stratum"]==s],gates.ROOTS_PER_STRATUM)
        # Freeze exact selected request files and metadata before any value
        # evaluation, including unit calibration. No holdout-driven retries.
        frozen=dict(schema=1,split_sha256=split_sha,requests=chosen,
                    corpus_sha256={s:file_sha(out/(s+".json")) for s in corpora})
        write_private(out/"gate-manifest.json",canonical(frozen),False)
        meta=metadata(commit,split_sha,args.training_commit,args.training_dirty)
        hashes=feature_hashes(features,cols)
        calibration=calibrate(out,corpora["calibration"]["requests"],flat,model,params,oracle,engine,meta,hashes,runner,kind)
        calibration_sha=file_sha(out/"calibration.json")
        tensors,scales,quant=integer_parameters(flat,calibration["selected_unit"])
        artifact=pack_artifact(tensors,scales,engine,TEACHER,calibration_sha,meta,*hashes)
        duplicate=pack_artifact(*integer_parameters(flat,calibration["selected_unit"])[:2],engine,TEACHER,
                                calibration_sha,meta,*hashes)
        if artifact!=duplicate:fail("bc6_export_reproduction")
        path=out/"bc6-full.dfeval";digest=sha(artifact)
        export_manifest=dict(teacher_sha256=TEACHER,engine=engine,seed=split["seed"],
            source_training=dict(commit=args.training_commit,dirty=args.training_dirty),
            quantization=dict(method=METHOD,unit=calibration["selected_unit"]),
            split=dict(path=str(out/"split.json"),sha256=split_sha),
            calibration=dict(path=str(out/"calibration.json"),sha256=calibration_sha))
        write_private(out/"export-manifest.json",canonical(export_manifest),False)
        command=[sys.executable,str(ROOT/"tools/eval/export_bc6.py"),"--repo",str(ROOT),
            "--checkpoint",str(checkpoint_path),"--manifest",str(out/"export-manifest.json"),
            "--output",str(path),"--audit",str(out/"export-audit-private.json")]
        subprocess.run(command,check=True)
        subprocess.run([*command,"--check"],check=True)
        if path.read_bytes()!=artifact:fail("bc6_export_checker_mismatch")
        audit=dict(schema=1,teacher_sha256=TEACHER,artifact_sha256=digest,engine=engine,source_config=config,
            source_training=dict(commit=args.training_commit,dirty=args.training_dirty),export_commit=commit,
            export_dirty=False,inventory=inventory,omitted=omitted,quantization=quant,
            split_sha256=split_sha,calibration_sha256=calibration_sha,gate_manifest_sha256=file_sha(out/"gate-manifest.json"),
            runtime=dict(python=platform.python_version(),numpy=np.__version__,jax=jax.__version__,machine=platform.machine()))
        write_private(out/"audit-private.json",canonical(audit),False)
        # Independent integer intermediates on a deterministic balanced prefix.
        trace_rows=[]
        for r in chosen[:gates.ROOTS_PER_STRATUM][:TRACE_ROWS//2]+chosen[gates.ROOTS_PER_STRATUM:][:TRACE_ROWS//2]:
            from bc6_check import load_request
            req=load_request(out,r);ids=np.flatnonzero(req["open"])
            if ids.size:trace_rows.append(req["rows"][ids[0]])
        if len(trace_rows)!=TRACE_ROWS:fail("bc6_trace_coverage")
        trace_rows=np.array(trace_rows,np.float32)
        expected=integer_trace(calibration["selected_unit"],tensors,scales,trace_rows)
        runners=[runner,*args.runner];streams=[];cells=set();results=[]
        for i,exe in enumerate(runners):
            exe=exe.resolve();identity=subprocess.check_output([str(exe),"--identity"],text=True).split()
            if len(identity)!=4:fail("bc6_runner_identity")
            cells.add(tuple(identity[:2]));trace=out/f"trace-{i}.bin"
            with Runner(exe,path,digest,kind,trace,TRACE_ROWS) as native:native.values(trace_rows)
            if trace.read_bytes()!=expected:fail("bc6_integer_intermediate_mismatch")
            errs,decs,cov,groups,counts,stream,intervals=evaluate(out,chosen,exe,path,digest,kind,model,params,oracle,
                split["live_rule"],SEARCH["lam"],split["solver"])
            streams.append(stream)
            results.append(dict(identity=identity,binary_sha256=file_sha(exe),values_sha256=stream,
                                intermediate_sha256=file_sha(trace)))
            if len(set(streams))!=1:fail("bc6_compiler_value_mismatch")
            numeric=gates.report(errs,decs,groups=groups,coverage=cov,mechanics=True,reproduction=True,oracle=True)
        matrix=not (MATRIX-cells)
        numeric["gates"]["compiler_platform_matrix"]=matrix
        numeric["gates"]["exact_terminal_coverage"]=counts.get("terminal",0)>0
        numeric["gates"]["exact_cutoff_coverage"]=counts.get("cutoff_rows",0)>0
        numeric["fidelity_pass"]=all(numeric["gates"].values())
        numeric.update(commit=commit,dirty=False,machine=platform.machine(),system=platform.system(),
            teacher_sha256=TEACHER,artifact_sha256=digest,artifact_bytes=len(artifact),
            split_sha256=split_sha,calibration_sha256=calibration_sha,
            activation_calibration_sample=calibration["activation_sample"],
            gate_manifest_sha256=file_sha(out/"gate-manifest.json"),profiles=results,
            missing_platforms=sorted([list(c) for c in MATRIX-cells]),counts=counts,
            generation_refusals={s:corpora[s]["refusals"] for s in corpora},
            confidence_95=dict(method="2000 game-cluster bootstrap; fixed seed 0x2026101500040003",means=intervals),
            scope="private full-BC6 conversion; no adoption, training, distillation or timing claim")
        write_private(out/"gate-summary.json",canonical(numeric),False)
        print(json.dumps(dict(artifact_sha256=digest,fidelity_pass=numeric["fidelity_pass"],
                              report="gate-summary.json",missing_platforms=numeric["missing_platforms"])),flush=True)
        return 0 if numeric["fidelity_pass"] else 3
    finally:
        os.umask(old_umask)


if __name__=="__main__":
    try:sys.exit(main())
    except (ValueError,KeyError,OSError,subprocess.SubprocessError,zipfile.BadZipFile) as error:
        # The full diagnostic stays local; don't include checkpoint or rows in
        # a public exception. A failed run is never reported as gate-passed.
        print("bc6_local_run_failed: "+str(error),file=sys.stderr);sys.exit(2)
