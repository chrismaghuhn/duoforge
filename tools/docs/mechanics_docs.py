"""The mechanic docs: generate docs/support/README.md and check the decision 0015 entry ids (restructure step 11).

    python3 tools/docs/mechanics_docs.py --write   # regenerate docs/support/README.md
    python3 tools/docs/mechanics_docs.py --check   # the README is up to date, and every entry id resolves

docs/support/README.md is made of three sources and is never edited by hand:
- docs/support/README.template.md: the rows that belong to no mechanic file (the foundation, the gates, the licensing
  facts), with three placeholder lines;
- the "## Support" section of every mechanic file (docs/mechanics/<area>/<id>-<slug>.md), in entry id order: table
  rows ("| ... |") go after the template's table rows, the other lines become paragraphs;
- src/data/support_manifest.c: how many ids it marks per kind and which view extension features it supports.

The id check: every mechanic file starts with exactly one anchor, its entry id; every id is in one file only; every row
of the frozen redirect table of decision 0015 (section 4.3) resolves to its file and anchor; and every id that a
tracked text file cites on a line that names 0015 is an anchor or a "no entry" row of that table.

Standard library only; paths through pathlib, UTF-8, "\n" line ends on write, so the output is the same on Windows.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MECHANICS = Path("docs/mechanics")
AREAS = ("flow", "mechanics", "items", "abilities", "moves", "forms", "field")
README = Path("docs/support/README.md")
TEMPLATE = Path("docs/support/README.template.md")
MANIFEST = Path("src/data/support_manifest.c")
DECISION = Path("docs/decisions/0015-content-expansion-pool.md")
PH_ROWS = "<!-- mechanic table rows -->"
PH_PARAS = "<!-- mechanic paragraphs -->"
PH_MANIFEST = "<!-- support manifest -->"
GENERATED = ("<!-- Generated by tools/docs/mechanics_docs.py from docs/support/README.template.md, the \"## Support\" "
             "sections of docs/mechanics and src/data/support_manifest.c; do not edit, run "
             "`python3 tools/docs/mechanics_docs.py --write`. -->")
ID = re.compile(r"^5[a-z]{1,2}$")
# The one id that decision 0015 gave twice (HS, 2026-10-23): K4 Gravity keeps 5dl, the Illusion entry of issue 556
# is 5dl-556. No other suffixed id is allowed.
SPECIAL_IDS = {"5dl-556"}
ANCHOR = re.compile(r'^<a id="([^"]+)"></a>$')
CITES_0015 = re.compile(r"(?<![\w.])0015(?!\w)")
CITED = re.compile(r"(?<![\w-])5[a-z]{1,2}(?![\w])")
NOT_IDS = {"5th", "5ms", "5px", "5kb", "5mb", "5gb"}  # units and ordinals, never entry ids
BODY = re.compile(r"^(5[a-z]{1,2})\. \*\*")
ROW = re.compile(r"^\| (5[a-z]{1,2}(?:-[0-9]+)?) \| [^|]* \| (?:[^|]|\\\|)* \| (.*) \|$")
LINK = re.compile(r"^\[[^\]]+\]\(\.\./mechanics/([^)#]+)#([^)]+)\)$")


def read(rel):
    return (ROOT / rel).read_text(encoding="utf-8")


def id_key(i):
    base = i.split("-")[0]
    return (len(base), base, i)


def mechanic_files():
    out = []
    for area in AREAS:
        out += sorted((ROOT / MECHANICS / area).glob("*.md"))
    stray = [p for p in (ROOT / MECHANICS).rglob("*.md")
             if p not in out and p.parent != ROOT / MECHANICS]
    return out, stray


def parse_mechanic(path):
    """(id, problems, support blocks). A support block is one table row or one paragraph (consecutive lines)."""
    lines = read(path.relative_to(ROOT)).splitlines()
    m = ANCHOR.match(lines[0]) if lines else None
    ident = m.group(1) if m else None
    problems = []
    if ident is None:
        return None, ["the first line is not the entry's anchor <a id=\"<id>\"></a>"], []
    anchors = sum(1 for l in lines if ANCHOR.match(l))
    if anchors != 1:
        problems.append("%d anchors, want 1" % anchors)
    if len(lines) < 3 or lines[1] != "" or not lines[2].startswith("# %s. " % ident):
        problems.append("line 3 is not the heading '# %s. <title>'" % ident)
    for key, want in (("Area", path.parent.name), ("Step", None), ("Tests", None)):
        found = [l for l in lines if l.startswith("- %s: " % key)]
        if len(found) != 1:
            problems.append("%d '- %s: ' lines, want 1" % (len(found), key))
        elif want is not None and found[0] != "- %s: %s" % (key, want):
            problems.append("'%s' does not name its folder %s" % (found[0], want))
    body = [BODY.match(l).group(1) for l in lines if BODY.match(l)]
    if len(body) != 1 or body[0] != ident.split("-")[0]:
        problems.append("the entry text must start once with '%s. **' (found %s)" % (ident.split("-")[0], body))
    heads = [l for l in lines if l.startswith("## ")]
    if any(h.rstrip() == "## Support" and h != "## Support" for h in heads) or heads.count("## Support") > 1:
        problems.append("the support heading must be exactly '## Support', once")
    support = []
    if "## Support" in lines:
        k = lines.index("## Support") + 1
        para = []
        while k < len(lines) and not lines[k].startswith("#"):
            line = lines[k]
            if line.startswith("|"):
                if para:
                    support.append("\n".join(para))
                    para = []
                support.append(line)
            elif line.strip():
                para.append(line)
            elif para:
                support.append("\n".join(para))
                para = []
            k += 1
        if para:
            support.append("\n".join(para))
        if not support:
            problems.append("an empty '## Support' section; leave it out")
    return ident, problems, support


def manifest_section():
    text = read(MANIFEST)
    body = text[text.index("const dfi_support_manifest dfi_support = {"):]
    out = ["## Marked in the support manifest", "", GENERATED.replace("from docs/support/README.template.md, the "
                                                                       "\"## Support\" sections of docs/mechanics and ",
                                                                       "from "), "",
           "The counts of `src/data/support_manifest.c` (all ids of the pool tables, the closure and Team C included).",
           "", "| Kind | Marked |", "|---|---|"]
    for flag in ("turn_core", "switching", "mega_evolution"):
        m = re.search(r"^\s*\.%s = ([01])u," % flag, body, re.M)
        if not m:
            raise SystemExit("support manifest: flag .%s not found" % flag)
        out.append("| `%s` | %s |" % (flag, "yes" if m.group(1) == "1" else "no"))
    for kind, field in (("MOVE", "moves"), ("ABILITY", "abilities"), ("ITEM", "items")):
        start = body.index(".%s =" % field)
        block = body[start:body.index("},", start)]
        marks = re.findall(r"^\s*\[DFI_%s_[A-Z0-9_]+\] = 1u," % kind, block, re.M)
        if not marks or re.search(r"^\s*\[DFI_%s_[A-Z0-9_]+\] = (?!1u,)" % kind, block, re.M):
            raise SystemExit("support manifest: the .%s block has a form this generator does not read" % field)
        out.append("| %s | %d |" % (field, len(marks)))
    start = body.index(".view_ext_features =")
    feats = []
    for f in re.findall(r"DUOFORGE_VIEWEXT_FEATURE_([A-Z0-9_]+)", body[start:body.index(";", start)]):
        if f not in feats:
            feats.append(f)
    out.append("| view extension features | %d: %s |" % (len(feats), ", ".join("`%s`" % f for f in feats)))
    return out


def generate():
    files, _ = mechanic_files()
    rows, paras = [], []
    for path in sorted(files, key=lambda p: id_key(parse_mechanic(p)[0] or "")):
        for block in parse_mechanic(path)[2]:
            (rows if block.startswith("|") else paras).append(block)
    out = [GENERATED]
    for line in read(TEMPLATE).splitlines():
        if line == PH_ROWS:
            out += rows
        elif line == PH_PARAS:
            for k, p in enumerate(paras):
                out += ([""] if k else []) + [p]
        elif line == PH_MANIFEST:
            out += manifest_section()
        else:
            out.append(line)
    return "\n".join(out) + "\n"


def tracked_text():
    try:
        res = subprocess.run(["git", "ls-files", "-z"], cwd=ROOT, capture_output=True, check=True)
    except (OSError, subprocess.CalledProcessError) as exc:
        raise SystemExit("the citation check needs a git checkout: %s" % exc)
    for rel in res.stdout.decode("utf-8").split("\0"):
        if not rel:
            continue
        try:
            yield rel, (ROOT / rel).read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue


def check_ids():
    errors = []
    files, stray = mechanic_files()
    errors += ["%s: a mechanic file must be in one of the areas %s" % (p.relative_to(ROOT).as_posix(), ", ".join(AREAS))
               for p in stray]
    where = {}
    for p in files:
        rel = p.relative_to(ROOT / MECHANICS).as_posix()
        ident, problems, _ = parse_mechanic(p)
        errors += ["%s: %s" % (rel, e) for e in problems]
        if ident is None:
            continue
        if not (ID.match(ident) or ident in SPECIAL_IDS):
            errors.append("%s: %r is not an entry id" % (rel, ident))
        if not p.name.startswith(ident + "-"):
            errors.append("%s: the file name does not start with its id %s-" % (rel, ident))
        if ident in where:
            errors.append("id %s is in %s and %s" % (ident, where[ident], rel))
        where[ident] = rel

    table, no_entry = {}, set()
    for line in read(DECISION).splitlines():
        m = ROW.match(line)
        if not m or m.group(1) == "Id":
            continue
        ident, target = m.group(1), m.group(2)
        if ident in table or ident in no_entry:
            errors.append("0015 table: id %s twice" % ident)
        link = LINK.match(target)
        if not link and "../mechanics/" in target:
            errors.append("0015 table: row %s has a malformed link %r" % (ident, target))
        elif link:
            table[ident] = link.group(1)
            if where.get(link.group(2)) != link.group(1):
                errors.append("0015 table: %s -> %s#%s does not resolve" % (ident, link.group(1), link.group(2)))
            if link.group(2) != ident:
                errors.append("0015 table: row %s links the anchor %s" % (ident, link.group(2)))
        else:
            no_entry.add(ident)
            if ident in where:
                errors.append("0015 table: %s has a file but its row says no entry" % ident)
    if not table:
        errors.append("0015: the redirect table (section 4.3) was not found")
    errors += ["0015 table: %s has no row" % i for i in sorted(set(table) - set(where), key=id_key)]

    known = set(where) | no_entry
    cited = 0
    for rel, text in tracked_text():
        for n, line in enumerate(text.splitlines(), 1):
            if not CITES_0015.search(line):
                continue
            for ident in CITED.findall(line):
                if ident in NOT_IDS:
                    continue
                cited += 1
                if ident not in known:
                    errors.append("%s:%d cites 0015 entry %s, which resolves to no file and no table row"
                                  % (rel, n, ident))
    return errors, len(where), len(table), len(no_entry), cited


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true", help="regenerate docs/support/README.md")
    g.add_argument("--check", action="store_true", help="README up to date and every entry id resolves")
    g.add_argument("--check-readme", action="store_true", help="only the README")
    g.add_argument("--check-ids", action="store_true", help="only the entry ids")
    a = ap.parse_args(argv)
    if a.write:
        with open(ROOT / README, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(generate())
        print("wrote %s" % README.as_posix())
        return 0
    errors = []
    if a.check or a.check_readme:
        path = ROOT / README
        if not path.is_file() or path.read_text(encoding="utf-8") != generate():
            errors.append("%s is not what the generator makes; run python3 tools/docs/mechanics_docs.py --write"
                          % README.as_posix())
        else:
            print("README: up to date")
    if a.check or a.check_ids:
        id_errors, files, rows, no_entry, cited = check_ids()
        errors += id_errors
        if not id_errors:
            print("ids: %d mechanic files, %d table rows to files, %d no-entry rows, %d citations resolve"
                  % (files, rows, no_entry, cited))
    for e in errors:
        print("FAIL: %s" % e)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
