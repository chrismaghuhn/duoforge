#!/usr/bin/env python3
"""Generate private per-special move-phase tables; no Showdown checkout needed.

Usage: python tools/datagen/gen_move_handlers.py [--check]
The reader is the only adapter CF1 replaces with entry definitions; the table
schema, frozen special ids and rendered bytes remain the writer's contract.
"""
import argparse
from pathlib import Path
import re

from move_handler_source import rows


def render(entries):
    entries = tuple(entries)
    if (not entries or len(entries) > 256 or
            len({r.name for r in entries}) != len(entries) or
            any(r.value != i or re.fullmatch(r"[A-Z][A-Z0-9_]*", r.name) is None or
                type(r.hit_guard) is not bool or type(r.status_hit) is not bool
                for i, r in enumerate(entries))):
        raise ValueError("invalid move-handler rows")
    lines = ["#ifndef DUOFORGE_COMBAT_GENERATED_MOVE_HANDLERS_H",
             "#define DUOFORGE_COMBAT_GENERATED_MOVE_HANDLERS_H", "",
             "/* Generated by tools/datagen/gen_move_handlers.py; DO NOT EDIT.",
             " * Phase eligibility, not the support manifest or an overall handler registry. */",
             '#include "data/formats/reg-mc/pool_tables.h"', "",
             f"#define DFI_SPECIAL_COUNT {len(entries)}u", ""]
    lines += [f'_Static_assert(DFI_SPECIAL_{r.name} == {r.value}u, "frozen special {r.name}");'
              for r in entries]
    lines += [""]
    for field, name in [("hit_guard", "dfi_special_has_handler"),
                        ("status_hit", "dfi_special_status_hit")]:
        lines += [f"static const uint8_t {name}[DFI_SPECIAL_COUNT] = {{"]
        lines += [f"    {int(getattr(r, field))}u, /* {r.value}: {r.name} */" for r in entries]
        lines += ["};", ""]
    return "\n".join(lines + ["#endif", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[2] / "src/combat/generated/move_handlers.h"
    data = render(rows()).encode("ascii")
    if args.check:
        if not target.is_file() or target.read_bytes().replace(b"\r\n", b"\n") != data:
            parser.exit(1, f"{target}: differs from generated move handler tables\n")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    print(f"move handlers: {len(rows())} specials ({'check ok' if args.check else 'generated'})")


if __name__ == "__main__":
    main()
